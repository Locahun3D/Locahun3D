import fs from 'node:fs';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {shipped,bodies,sections} from './perf-wasm-tools.mjs';
const dir='F:/Codex/locahun-performance-20260911/';
const hash=b=>createHash('sha256').update(b).digest('hex');
const original=shipped(),candidate=fs.readFileSync(dir+'candidate-worker.wasm');
assert.equal(hash(original.bundle),'d2d5a26e30d1f95b7dd7eeb5378976caa07c20fa81cdbe745b8fa900f6e761be','source changed: review before assembling');
assert(WebAssembly.validate(candidate));
const oldSections=sections(original.bytes),newSections=sections(candidate);
assert.deepEqual(newSections.map(s=>s.id),oldSections.map(s=>s.id));
for(let i=0;i<oldSections.length;i++)if(oldSections[i].id!==10)assert.deepEqual(newSections[i].data,oldSections[i].data,'non-code section unchanged');
const oldBodies=bodies(original.bytes),newBodies=bodies(candidate);
assert.equal(oldBodies.length,newBodies.length);
const imports=WebAssembly.Module.imports(new WebAssembly.Module(original.bytes)).filter(x=>x.kind==='function').length;
const changed=oldBodies.flatMap((b,i)=>b.equals(newBodies[i])?[]:[i+imports]);
assert.deepEqual(changed,[319],'only heap pop may change');
const worker=original.worker.replace(original.encoded,candidate.toString('base64'));
assert.notEqual(worker,original.worker);
const start=original.bundle.indexOf('const jsContent = '),end=original.bundle.indexOf('\n',start);
const bundle=original.bundle.slice(0,start)+'const jsContent = '+JSON.stringify(worker)+';'+original.bundle.slice(end);
fs.writeFileSync(dir+'spark-heap-candidate.module.js',bundle);
const manifest={upstreamVersion:'2.0.0',upstreamCommit:'ea56ee73f1ec015deac852998870e1dc80f21a7f',originalBundleSha256:hash(original.bundle),originalWasmSha256:hash(original.bytes),candidateWasmSha256:hash(candidate),candidateBundleSha256:hash(bundle),rustSourceSha256:hash(fs.readFileSync(dir+'heap-pop.rs')),changedFunctions:changed,scope:'isolated artifact only; NOT approved for production or visual quality'};
fs.writeFileSync(dir+'heap-candidate-manifest.json',JSON.stringify(manifest,null,2));
console.log(manifest);
