import {readFileSync} from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const ctx = vm.createContext({console});
vm.runInContext(readFileSync(new URL('../src/js/216_walk_settings.js',import.meta.url),'utf8'),ctx);
const parse = x => JSON.parse(JSON.stringify(ctx.LocahunWalkSettings.parse(x)));
assert.equal(parse(null).cellSize,.25);
assert.deepEqual(parse({whole:{key:'a'.repeat(64),data:'AAAA'}}).whole,{key:'a'.repeat(64),data:'AAAA'});
assert.equal(parse({whole:{key:'bad',data:'AAAA'}}).whole,null);
assert.equal(parse({cellSize:0}).cellSize,.25);
assert.equal(parse({cellSize:100}).cellSize,.25);
assert.equal(parse({cellSize:.4}).cellSize,.4);
assert.deepEqual(parse({meshIds:[1,1,'bad',3]}).meshIds,[1,3]);
assert.deepEqual(parse({excludeIds:[2,2,'bad',4]}).excludeIds,[2,4]);
assert.equal(parse({spawn:{x:1,y:NaN,z:3}}).spawn,null);
assert.deepEqual(parse({spawn:{x:1,y:-2,z:3}}).spawn,{x:1,y:-2,z:3});
assert.throws(()=>parse({boxes:[{center:[0,0,0],half:[-1,1,1]}]}));
assert.throws(()=>parse({boxes:new Array(30001).fill({center:[0,0,0],half:[1,1,1]})}));
assert.deepEqual(parse({boxes:[{center:[0,-1,0],half:[1,.1,2]}]}).boxes,[{center:[0,-1,0],half:[1,.1,2]}]);
console.log('walk settings assertions passed');
